CREATE TABLE IF NOT EXISTS category (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS game (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  enterprise VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS user (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  address VARCHAR(255) NOT NULL,
  phone_number VARCHAR(20) DEFAULT NULL,
  role VARCHAR(45) NOT NULL DEFAULT 'user'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS product (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  description LONGTEXT NOT NULL,
  price DECIMAL(12,2) NOT NULL,
  stock INT UNSIGNED NOT NULL,
  image_path VARCHAR(255),
  user_id INT UNSIGNED NOT NULL,
  category_id INT UNSIGNED NOT NULL,
  game_id INT UNSIGNED NOT NULL,
  archived_at TIMESTAMP NULL,
  version INT UNSIGNED NOT NULL DEFAULT 0,
  CONSTRAINT product_nonnegative_price CHECK (price >= 0),
  CONSTRAINT product_user_fk FOREIGN KEY (user_id) REFERENCES user (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT product_category_fk FOREIGN KEY (category_id) REFERENCES category (id),
  CONSTRAINT product_game_fk FOREIGN KEY (game_id) REFERENCES game (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `order` (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  status VARCHAR(100) NOT NULL,
  closed_at TIMESTAMP NULL,
  open_user_id INT UNSIGNED GENERATED ALWAYS AS (CASE WHEN status = 'open' THEN user_id END) VIRTUAL,
  UNIQUE KEY order_one_open_per_user (open_user_id),
  KEY order_user_status (user_id, status),
  CONSTRAINT order_user_fk FOREIGN KEY (user_id) REFERENCES user (id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS order_item (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  product_id INT UNSIGNED NOT NULL,
  order_id INT UNSIGNED NOT NULL,
  quantity INT UNSIGNED NOT NULL,
  snapshot_name VARCHAR(255),
  snapshot_description LONGTEXT,
  snapshot_price DECIMAL(12,2),
  snapshot_image_path VARCHAR(255),
  snapshot_game VARCHAR(255),
  snapshot_category VARCHAR(255),
  UNIQUE KEY order_item_once_per_product (order_id, product_id),
  CONSTRAINT order_item_positive_quantity CHECK (quantity > 0),
  CONSTRAINT item_order_fk FOREIGN KEY (order_id) REFERENCES `order` (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT item_product_fk FOREIGN KEY (product_id) REFERENCES product (id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
